"""Interactive browser test for /drift-guard diagnostic, GA4 gate_simulator_run, and UTM preservation."""
import json
import os
import subprocess
import urllib.parse
import uuid

origin = os.environ.get('SITE_TEST_ORIGIN', 'http://127.0.0.1:4180').rstrip('/')
target = urllib.parse.urlsplit(origin)
if target.scheme != 'http' or target.hostname not in ('127.0.0.1', 'localhost', '::1'):
    raise ValueError('Drift guard browser checks require a local HTTP server.')

em_dash = '\u2014'
custom_slop = (
    f"In today's digital age, this agent wasn't just an assistant, it was a paradigm shift{em_dash}"
    'highlighting pivotal safeguards across the workflow. '
    'The report was generated by the model behind closed doors to bolster alignment. '
    'Notably, these meticulous checks showcase a holistic approach.'
)

commands = [
    ['set', 'viewport', '1440', '1000'],
    ['open', origin + '/drift-guard?utm_source=gsc-test&utm_medium=organic&utm_campaign=drift-guard&utm_content=hero&debug_mode=1'],
    ['wait', '#drift-guard-input'],
    ['eval', '(()=>{if(document.documentElement.scrollWidth>innerWidth)throw Error("Desktop overflow on /drift-guard");return true})()'],
    ['eval', 'document.querySelector(\'[data-drift-preset="operator-incident-note"]\').scrollIntoView({block:"center",behavior:"instant"})'],
    ['click', '[data-drift-preset="operator-incident-note"]'],
    ['wait', '--fn', 'document.querySelector("[data-drift-verdict]").getAttribute("data-drift-verdict") === "PASS"'],
    ['eval', 'document.querySelector("#drift-guard-input").scrollIntoView({block:"center",behavior:"instant"})'],
    ['fill', '#drift-guard-input', custom_slop],
    ['eval', 'document.querySelector("[data-drift-run]").scrollIntoView({block:"center",behavior:"instant"})'],
    ['click', '[data-drift-run]'],
    ['wait', '--fn', 'document.querySelector("[data-drift-verdict]").getAttribute("data-drift-verdict") === "FAIL"'],
    ['eval', """(() => {
      const dashes = document.querySelector('[data-metric="long-dashes"]').textContent.trim();
      if (dashes !== '1') throw Error('Expected 1 long dash, got ' + dashes);
      const marks = document.querySelectorAll('[data-drift-highlight-preview] mark').length;
      if (marks < 3) throw Error('Expected highlighted slop spans, got ' + marks);
      const events = (window.dataLayer || []).filter(e => e && e.event === 'gate_simulator_run');
      if (events.length !== 2) throw Error('Expected 2 gate_simulator_run events, got ' + events.length);
      const last = events[1];
      if (last.utm_source !== 'gsc-test' || last.utm_campaign !== 'drift-guard' || last.debug_mode !== true) {
        throw Error('Missing UTM or debug_mode on gate_simulator_run: ' + JSON.stringify(last));
      }
      if (JSON.stringify(events).includes('behind closed doors')) {
        throw Error('Pasted prose leaked into dataLayer');
      }
      const ctaHref = document.querySelector('[data-drift-pilot-cta]').getAttribute('href');
      if (!ctaHref || !ctaHref.includes('utm_source=gsc-test')) {
        throw Error('Pilot CTA dropped incoming UTM attribution: ' + ctaHref);
      }
      return { dashes, marks, eventsCount: events.length, ctaHref };
    })()"""],
    ['eval', 'document.querySelector("[data-drift-pilot-cta]").scrollIntoView({block:"center",behavior:"instant"})'],
    ['click', '[data-drift-pilot-cta]'],
    ['wait', '--fn', 'location.pathname === "/waitlist" && location.search.includes("utm_source=gsc-test")'],
    ['set', 'viewport', '390', '844'],
    ['open', origin + '/drift-guard'],
    ['wait', '#drift-guard-input'],
    ['eval', '(()=>{if(document.documentElement.scrollWidth>innerWidth)throw Error("Mobile 390px overflow on /drift-guard");return true})()'],
    ['errors'],
]

session = 'cosmocrat-drift-guard-' + uuid.uuid4().hex[:10]
env = os.environ.copy()
for key in ('AUTO_CONNECT', 'PROFILE', 'STATE', 'SESSION_NAME', 'PROVIDER', 'CDP'):
    env.pop('AGENT_BROWSER_' + key, None)
base = ['agent-browser', '--session', session]
try:
    result = subprocess.run(
        base + ['batch', '--bail', '--json'],
        input=json.dumps(commands),
        capture_output=True,
        text=True,
        env=env,
        timeout=180,
    )
    print(result.stdout)
    if result.stderr:
        print(result.stderr)
    result.check_returncode()
    records = json.loads(result.stdout)
    assert len(records) == len(commands) and all(r['success'] for r in records)
    assert records[-1]['result']['errors'] == [], records[-1]
    print(f'PASS: {len(commands)} drift-guard browser checks')
finally:
    subprocess.run(base + ['close'], env=env, capture_output=True, timeout=20)
